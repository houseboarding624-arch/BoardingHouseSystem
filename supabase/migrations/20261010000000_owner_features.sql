-- Owner dashboard features: unlimited beds per room, auto room status,
-- tenant billing cycle + termination, notifications (curfew / payment),
-- reservations, expenses, maintenance, announcements, audit log, settings.

-- ---------------------------------------------------------------- rooms
alter table public.rooms
    add column if not exists beds integer not null default 1;
alter table public.rooms drop constraint if exists rooms_beds_check;
alter table public.rooms add constraint rooms_beds_check check (beds >= 1);

-- ---------------------------------------------------------------- users
alter table public.users add column if not exists status varchar(20) not null default 'Active';
alter table public.users drop constraint if exists users_status_check;
alter table public.users add constraint users_status_check check (status in ('Active', 'Terminated'));
alter table public.users add column if not exists move_in_date date;
alter table public.users add column if not exists next_due_date date;
alter table public.users add column if not exists due_notice_for date;
alter table public.users add column if not exists terminated_at timestamptz;
alter table public.users add column if not exists termination_reason varchar(255);

-- ------------------------------------------------------------- payments
alter table public.payments add column if not exists type varchar(20) not null default 'Rent';
alter table public.payments drop constraint if exists payments_type_check;
alter table public.payments add constraint payments_type_check check (type in ('Rent', 'Deposit', 'Other'));
alter table public.payments add column if not exists proof_ref varchar(255);
alter table public.payments add column if not exists verified boolean not null default false;

-- --------------------------------------------------------- new tables
create table if not exists public.notifications (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.users(id) on delete cascade,
    type varchar(30) not null default 'Manual',
    title varchar(150) not null,
    message text not null,
    email_status varchar(20) not null default 'skipped',
    email_error text,
    is_read boolean not null default false,
    created_at timestamptz not null default now()
);

create table if not exists public.announcements (
    id bigint generated by default as identity primary key,
    title varchar(150) not null,
    body text not null,
    created_at timestamptz not null default now()
);

create table if not exists public.expenses (
    id bigint generated by default as identity primary key,
    category varchar(60) not null,
    description varchar(255),
    amount numeric(10,2) not null check (amount > 0),
    expense_date date not null,
    created_at timestamptz not null default now()
);

create table if not exists public.reservations (
    id bigint generated by default as identity primary key,
    full_name varchar(150) not null,
    contact varchar(30),
    email varchar(150),
    room_number varchar(20),
    reserved_for date,
    notes varchar(255),
    status varchar(20) not null default 'Pending'
        check (status in ('Pending', 'Confirmed', 'Cancelled')),
    created_at timestamptz not null default now()
);

create table if not exists public.maintenance_requests (
    id bigint generated by default as identity primary key,
    room_number varchar(20),
    issue varchar(255) not null,
    cost numeric(10,2) not null default 0,
    status varchar(20) not null default 'Open'
        check (status in ('Open', 'In Progress', 'Done')),
    created_at timestamptz not null default now()
);

create table if not exists public.audit_logs (
    id bigint generated by default as identity primary key,
    actor_name varchar(150),
    action varchar(80) not null,
    details text,
    created_at timestamptz not null default now()
);

create table if not exists public.app_settings (
    key varchar(60) primary key,
    value text not null
);

create index if not exists idx_notifications_user on public.notifications(user_id, created_at desc);
create index if not exists idx_expenses_date on public.expenses(expense_date);
create index if not exists idx_users_next_due on public.users(next_due_date);

alter table public.notifications enable row level security;
alter table public.announcements enable row level security;
alter table public.expenses enable row level security;
alter table public.reservations enable row level security;
alter table public.maintenance_requests enable row level security;
alter table public.audit_logs enable row level security;
alter table public.app_settings enable row level security;
