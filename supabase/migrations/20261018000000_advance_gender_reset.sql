-- 1) "Deposit" payments become "Advance Payment".
alter table public.payments drop constraint if exists payments_type_check;
alter table public.gcash_payments drop constraint if exists gcash_payments_type_check;
update public.payments set type = 'Advance Payment' where type = 'Deposit';
update public.gcash_payments set type = 'Advance Payment' where type = 'Deposit';
alter table public.payments
    add constraint payments_type_check check (type in ('Rent', 'Advance Payment', 'Other'));
alter table public.gcash_payments
    add constraint gcash_payments_type_check check (type in ('Rent', 'Advance Payment', 'Other'));

-- 2) A recorded payment is Paid automatically (the "verified" column now means Paid / Unpaid).
alter table public.payments alter column verified set default true;
-- Existing recorded payments were all waiting for a manual "Verify"; they were paid, so mark them Paid.
-- (Delete this line if you want to keep the old flags.)
update public.payments set verified = true where verified = false;

-- 3) Gender chosen at sign-up.
alter table public.users add column if not exists gender varchar(10);
alter table public.users drop constraint if exists users_gender_check;
alter table public.users add constraint users_gender_check check (gender is null or gender in ('Male', 'Female'));

-- 4) Forgot-password codes (stored hashed, expire, limited attempts).
create table if not exists public.password_resets (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.users(id) on delete cascade,
    code_hash varchar(100) not null,
    attempts integer not null default 0,
    expires_at timestamptz not null,
    used_at timestamptz,
    created_at timestamptz not null default now()
);
create index if not exists idx_password_resets_user on public.password_resets(user_id, created_at desc);
alter table public.password_resets enable row level security;
