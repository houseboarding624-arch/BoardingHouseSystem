-- Boarder reports (complaints) and GCash payment submissions.

create table if not exists public.reports (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.users(id) on delete cascade,
    category varchar(30) not null default 'Other',
    subject varchar(120) not null,
    message text not null,
    status varchar(20) not null default 'New'
        check (status in ('New', 'In Progress', 'Resolved')),
    admin_reply text,
    resolved_at timestamptz,
    created_at timestamptz not null default now()
);

create table if not exists public.gcash_payments (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.users(id) on delete cascade,
    amount numeric(10,2) not null check (amount > 0),
    type varchar(20) not null default 'Rent' check (type in ('Rent', 'Deposit', 'Other')),
    reference_no varchar(30) not null unique,
    sender_number varchar(20),
    note varchar(255),
    status varchar(20) not null default 'Pending'
        check (status in ('Pending', 'Approved', 'Rejected')),
    reject_reason varchar(255),
    payment_id bigint references public.payments(id) on delete set null,
    reviewed_at timestamptz,
    created_at timestamptz not null default now()
);

create index if not exists idx_reports_status on public.reports(status, created_at desc);
create index if not exists idx_reports_user on public.reports(user_id);
create index if not exists idx_gcash_status on public.gcash_payments(status, created_at desc);
create index if not exists idx_gcash_user on public.gcash_payments(user_id);

alter table public.reports enable row level security;
alter table public.gcash_payments enable row level security;
