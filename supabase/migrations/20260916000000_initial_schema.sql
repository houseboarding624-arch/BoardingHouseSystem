create table if not exists public.users (
    id bigint generated by default as identity primary key,
    username varchar(100) not null unique,
    password varchar(255) not null,
    role varchar(20) not null check (role in ('Boarder', 'Admin', 'Owner')),
    full_name varchar(150) not null,
    contact varchar(30),
    email varchar(150) unique,
    address varchar(255),
    preferred_room varchar(20),
    created_at timestamptz not null default now()
);

create table if not exists public.rooms (
    id bigint generated by default as identity primary key,
    room_number varchar(20) not null unique,
    monthly_rate numeric(10,2) not null default 0,
    status varchar(20) not null default 'Available'
        check (status in ('Available', 'Occupied', 'Maintenance')),
    created_at timestamptz not null default now()
);

create table if not exists public.payments (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.users(id) on delete cascade,
    amount numeric(10,2) not null,
    payment_date date not null,
    description varchar(255),
    created_at timestamptz not null default now()
);

create table if not exists public.attendance (
    id bigint generated by default as identity primary key,
    user_id bigint not null references public.users(id) on delete cascade,
    attendance_date date not null,
    time_in timestamptz,
    time_out timestamptz,
    qr_token varchar(255),
    status varchar(10) not null default 'IN'
        check (status in ('IN', 'OUT')),
    created_at timestamptz not null default now(),
    unique (user_id, attendance_date)
);

create table if not exists public.qr_settings (
    id bigint generated by default as identity primary key,
    qr_name varchar(100) not null,
    qr_token varchar(255) not null unique,
    is_active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists idx_users_role on public.users(role);
create index if not exists idx_payments_user on public.payments(user_id);
create index if not exists idx_payments_date on public.payments(payment_date);
create index if not exists idx_attendance_user_date on public.attendance(user_id, attendance_date);

